"use strict";
const test=require("node:test"),assert=require("node:assert/strict");
const M=require("../app/src/main/assets/understanding/math-expression-model-v1.js");
const S=require("../app/src/main/assets/understanding/symbolic-algebra-engine-v1.js");
const a=(s,o)=>S.analyze(s,M,o);
const p=s=>{const r=a(s);assert.ok(r.polynomial,"polynomial attendu pour "+s);return new Map(r.polynomial.map(x=>[x.monomial,x.coefficient]));};
test("01 moteur local hors ligne",()=>assert.equal(S.diagnostics().offline,true));
test("02 version",()=>assert.equal(S.version,"1.0.0"));
test("03 conserve la source",()=>assert.equal(a("x + x").source,"x + x"));
test("04 résultat prêt",()=>assert.equal(a("x+x").ready,true));
test("05 réduit x+x",()=>assert.equal(p("x+x").get("x^1"),2));
test("06 réduit x-x",()=>assert.equal(p("x-x").size,0));
test("07 réduit 2x+3x",()=>assert.equal(p("2x+3x").get("x^1"),5));
test("08 réduit x+2x+3",()=>{const m=p("x+2x+3");assert.equal(m.get("x^1"),3);assert.equal(m.get(""),3);});
test("09 additionne les constantes",()=>assert.equal(p("2+3").get(""),5));
test("10 soustrait les constantes",()=>assert.equal(p("8-3").get(""),5));
test("11 multiplication constante",()=>assert.equal(p("4*5").get(""),20));
test("12 division numérique",()=>assert.equal(p("12/3").get(""),4));
test("13 supprime addition zéro",()=>assert.equal(a("x+0").simplifiedExpression,"x"));
test("14 supprime soustraction zéro",()=>assert.equal(a("x-0").simplifiedExpression,"x"));
test("15 supprime facteur un",()=>assert.equal(a("1*x").simplifiedExpression,"x"));
test("16 produit par zéro",()=>assert.equal(a("0*x").simplifiedExpression,"0"));
test("17 puissance un",()=>assert.equal(a("x^1").simplifiedExpression,"x"));
test("18 puissance zéro",()=>assert.equal(a("x^0").simplifiedExpression,"1"));
test("19 signes négatifs doubles",()=>assert.equal(a("--x").simplifiedExpression,"x"));
test("20 calcule signe négatif",()=>assert.equal(a("-(-3)").simplifiedExpression,"3"));
test("21 développe x(x+1)",()=>{const m=p("x*(x+1)");assert.equal(m.get("x^2"),1);assert.equal(m.get("x^1"),1);});
test("22 développe (x+1)(x+2)",()=>{const m=p("(x+1)*(x+2)");assert.equal(m.get("x^2"),1);assert.equal(m.get("x^1"),3);assert.equal(m.get(""),2);});
test("23 développe carré binôme",()=>{const m=p("(x+1)^2");assert.equal(m.get("x^2"),1);assert.equal(m.get("x^1"),2);assert.equal(m.get(""),1);});
test("24 développe différence de carrés",()=>{const m=p("(x-y)*(x+y)");assert.equal(m.get("x^2"),1);assert.equal(m.get("y^2"),-1);});
test("25 développe (x-1)^2",()=>{const m=p("(x-1)^2");assert.equal(m.get("x^2"),1);assert.equal(m.get("x^1"),-2);assert.equal(m.get(""),1);});
test("26 développe produit à deux variables",()=>{const m=p("(x+y)*(z+w)");assert.equal(m.size,4);});
test("27 développe cube simple",()=>{const m=p("(x+1)^3");assert.equal(m.get("x^3"),1);assert.equal(m.get("x^2"),3);assert.equal(m.get("x^1"),3);assert.equal(m.get(""),1);});
test("28 multiplication implicite",()=>{const m=p("2x");assert.equal(m.get("x^1"),2);});
test("29 puissance variable",()=>assert.equal(p("x^4").get("x^4"),1));
test("30 combine variables identiques",()=>assert.equal(p("x*y+2*x*y").get("x^1*y^1"),3));
test("31 distingue variables",()=>assert.equal(p("x+y").size,2));
test("32 ordonne les variables du monôme",()=>assert.equal(p("y*x").get("x^1*y^1"),1));
test("33 combine plusieurs monômes",()=>{const m=p("x*y+y*x");assert.equal(m.size,1);assert.equal(m.get("x^1*y^1"),2);});
test("34 conserve coefficients négatifs",()=>assert.equal(p("x-3x").get("x^1"),-2));
test("35 calcule parenthèses numériques",()=>assert.equal(p("(2+3)*4").get(""),20));
test("36 respecte priorité",()=>assert.equal(p("2+3*4").get(""),14));
test("37 fractions numériques",()=>assert.equal(p("(x+x)/2").get("x^1"),1));
test("38 division symbolique refusée en expansion polynomiale",()=>assert.equal(a("1/x").polynomial,null));
test("39 dénominateur nul non réduit",()=>assert.equal(a("x/0").polynomial,null));
test("40 fonction non polynomiale conservée",()=>assert.equal(a("sin(x)").polynomial,null));
test("41 racine symbolique conservée",()=>assert.equal(a("sqrt(x)").polynomial,null));
test("42 facteur commun x",()=>assert.equal(a("x^2+2x").factored,true));
test("43 facteur commun extrait",()=>assert.ok(a("x^2+2x").factoredExpression.includes("x")));
test("44 facteur numérique commun",()=>assert.equal(a("2x+4").factored,true));
test("45 coefficient commun extrait",()=>assert.ok(a("2x+4").factoredExpression.startsWith("2")));
test("46 facteur commun de deux variables",()=>assert.equal(a("x*y+x*z").factored,true));
test("47 aucune factorisation artificielle",()=>assert.equal(a("x+y").factored,false));
test("48 facteur commun puissance",()=>assert.equal(a("x^3+x^2").factored,true));
test("49 réduction avec trois termes",()=>{const m=p("2x+3x-x");assert.equal(m.get("x^1"),4);});
test("50 polynôme nul",()=>assert.equal(p("x-x").size,0));
test("51 conserve les inconnues",()=>assert.ok(a("alpha+alpha").simplifiedExpression.includes("alpha")));
test("52 journal de transformations",()=>assert.ok(a("x+x").steps.length>0));
test("53 compte les étapes",()=>assert.equal(a("x+x").metrics.stepCount,a("x+x").steps.length));
test("54 expression simplifiée déclarée",()=>assert.equal(a("x+x").simplified,true));
test("55 équation non transformée",()=>assert.equal(a("x+1=2").issues[0].code,"relation_not_transformed"));
test("56 inégalité non transformée",()=>assert.equal(a("x>2").simplified,false));
test("57 erreurs de syntaxe préservées",()=>assert.equal(a("(x+1").simplified,false));
test("58 résultat sérialisable",()=>assert.doesNotThrow(()=>JSON.stringify(a("(x+1)^2"))));
test("59 limite de termes configurable",()=>assert.equal(a("(x+y)^4",{maxTerms:2}).issues[0].code,"expansion_term_limit"));
test("60 limite de termes bornée",()=>assert.equal(a("x+x",{maxTerms:9999}).policy.maxExpansionTerms,256));
test("61 nombre constant devient AST numérique",()=>assert.equal(a("2+3").simplifiedAst.type,"number"));
test("62 ne résout aucune équation",()=>assert.equal(a("x=2").policy.equationsSolved,false));
test("63 diagnostics listent les limites",()=>assert.ok(S.diagnostics().limitations.length>=5));
test("64 transformation déclarée équivalente",()=>assert.equal(a("(x+1)^2").policy.transformationsAlgebraicallyEquivalent,true));
test("65 domaine à suivre explicitement",()=>assert.equal(a("x/x").policy.domainRestrictionsMayNeedSeparateTracking,true));
