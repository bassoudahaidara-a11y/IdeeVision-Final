const test=require("node:test");const assert=require("node:assert/strict");const P=require("../app/src/main/assets/engine/physics-mechanics-engine-v1.js");
const close=(a,b,e=1e-8)=>assert.ok(Math.abs(a-b)<=e,Math.abs(a-b)+" differs from tolerance");
test("01 addition vectorielle",()=>assert.deepEqual(P.add({x:1,y:2},{x:3,y:4}),{x:4,y:6,z:0}));
test("02 soustraction vectorielle",()=>assert.deepEqual(P.subtract({x:4,y:6},{x:1,y:2}),{x:3,y:4,z:0}));
test("03 norme vectorielle",()=>assert.equal(P.magnitude({x:3,y:4,z:0}),5));
test("04 produit scalaire",()=>assert.equal(P.dot({x:1,y:2},{x:3,y:4}),11));
test("05 multiplication vectorielle par scalaire",()=>assert.deepEqual(P.scaleVector({x:2,y:3},2),{x:4,y:6,z:0}));
test("06 deuxième loi de Newton accélération",()=>assert.deepEqual(P.acceleration({x:10,y:0},2),{x:5,y:0,z:0}));
test("07 calcul force résultante",()=>assert.deepEqual(P.newtonForce(2,{x:3,y:0}),{x:6,y:0,z:0}));
test("08 poids standard",()=>close(P.weight(1),9.80665));
test("09 cinématique accélération constante",()=>assert.deepEqual(P.kinematics(2,3,4),{position:32,velocity:14,displacement:32}));
test("10 vitesse moyenne",()=>assert.equal(P.averageSpeed(100,20),5));
test("11 accélération moyenne",()=>assert.equal(P.accelerationFromSpeeds(20,10,2),5));
test("12 mouvement circulaire",()=>{const r=P.circularMotion(10,5);assert.equal(r.centripetalAcceleration,20);assert.equal(r.angularSpeed,2);});
test("13 force centripète",()=>assert.equal(P.centripetalForce(2,10,5),40));
test("14 énergie cinétique",()=>assert.equal(P.kineticEnergy(2,3),9));
test("15 énergie potentielle gravitationnelle",()=>close(P.gravitationalPotentialEnergy(2,5),98.0665));
test("16 énergie mécanique",()=>assert.equal(P.mechanicalEnergy(10,20),30));
test("17 travail force parallèle",()=>assert.equal(P.work(10,3),30));
test("18 travail force perpendiculaire",()=>close(P.work(10,3,Math.PI/2),0));
test("19 puissance moyenne",()=>assert.equal(P.power(100,5),20));
test("20 rendement en pourcentage",()=>assert.equal(P.efficiency(80,100),80));
test("21 quantité de mouvement",()=>assert.deepEqual(P.momentum(2,{x:3,y:0}),{x:6,y:0,z:0}));
test("22 impulsion force-temps",()=>assert.deepEqual(P.impulse({x:4,y:0},2),{x:8,y:0,z:0}));
test("23 variation de quantité de mouvement",()=>assert.deepEqual(P.impulseFromMomentumChange(2,{x:1,y:0},{x:4,y:0}),{x:6,y:0,z:0}));
test("24 gravitation universelle",()=>close(P.gravitationalForce(1,1,1),6.67430e-11,1e-20));
test("25 loi de Hooke signe restaurateur",()=>assert.equal(P.springForce(100,.1),-10));
test("26 énergie élastique",()=>close(P.springEnergy(100,.2),2));
test("27 frottement",()=>assert.equal(P.frictionForce(.2,50),10));
test("28 composantes poids plan incliné",()=>{const r=P.inclineComponents(2,Math.PI/6);close(r.parallel,9.80665);close(r.perpendicular,16.98561605204533);});
test("29 moment d'une force",()=>assert.equal(P.torque(2,10),20));
test("30 énergie cinétique de rotation",()=>assert.equal(P.rotationalKineticEnergy(4,3),18));
test("31 moment cinétique",()=>assert.equal(P.angularMomentum(4,3),12));
test("32 masse volumique",()=>assert.equal(P.density(10,2),5));
test("33 pression",()=>assert.equal(P.pressure(100,2),50));
test("34 pression hydrostatique",()=>close(P.hydrostaticPressure(1000,2),19613.3));
test("35 poussée d'Archimède",()=>close(P.buoyantForce(1000,.001),9.80665));
test("36 période ressort",()=>close(P.springPeriod(1,4*Math.PI*Math.PI),1));
test("37 période pendule simple petite oscillation",()=>close(P.pendulumPeriod(9.80665/(4*Math.PI*Math.PI)),1));
test("38 fréquence du ressort",()=>close(P.springFrequency(1,4*Math.PI*Math.PI),1));
test("39 collision parfaitement inélastique conserve quantité mouvement",()=>{const r=P.solveLinearMomentumCollision(2,3,1,0);assert.equal(r.sharedFinalVelocity,2);assert.equal(r.initialMomentum,r.finalMomentum);});
test("40 conversion km vers m",()=>assert.equal(P.convert(2,"km","m"),2000));
test("41 conversion km/h vers m/s",()=>assert.equal(P.convert(36,"kph","mps"),10));
