test("12 projection droite",()=>assert.deepEqual(G.projectOnLine(p(2,3),G.lineThrough(p(0,0),p(1,0))),p(2,0)));
test("13 distance point-droite",()=>assert.equal(G.pointLineDistance(p(0,3),G.lineThrough(p(0,0),p(1,0))),3));
test("14 aire cercle",()=>assert.ok(Math.abs(G.circleArea(2)-4*Math.PI)<1e-9));
