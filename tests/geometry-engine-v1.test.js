test("19 refuse triangle invalide",()=>assert.throws(()=>G.triangleFromSides(1,2,9)));
test("20 classe triangle rectangle",()=>assert.equal(G.classifyTriangle(p(0,0),p(4,0),p(0,3)).angle,"right"));
test("21 angle droit",()=>assert.ok(Math.abs(G.angleAt(p(1,0),p(0,0),p(0,1))-Math.PI/2)<1e-9));
test("22 degrés vers radians",()=>assert.equal(G.degreesToRadians(180),Math.PI));
test("23 aire polygone",()=>assert.equal(G.polygonArea([p(0,0),p(4,0),p(4,3),p(0,3)]),12));
test("24 aire orientée",()=>assert.equal(G.polygonSignedArea([p(0,0),p(4,0),p(4,3),p(0,3)]),12));
test("25 périmètre polygone",()=>assert.equal(G.polygonPerimeter([p(0,0),p(4,0),p(4,3),p(0,3)]),14));
test("26 centroïde",()=>assert.deepEqual(G.polygonCentroid([p(0,0),p(4,0),p(4,2),p(0,2)]),p(2,1)));
test("27 point intérieur",()=>assert.equal(G.pointInPolygon(p(2,1),[p(0,0),p(4,0),p(4,3),p(0,3)]).inside,true));
test("28 point bordure",()=>assert.equal(G.pointInPolygon(p(2,0),[p(0,0),p(4,0),p(4,3),p(0,3)]).boundary,true));
test("29 intersection segments",()=>assert.deepEqual(G.segmentIntersection(p(0,0),p(2,2),p(0,2),p(2,0)),{kind:"point",point:p(1,1)}));
test("30 segments colinéaires",()=>assert.equal(G.segmentIntersection(p(0,0),p(1,0),p(2,0),p(3,0)).kind,"collinear"));
test("31 cercle droite deux points",()=>assert.equal(G.circleLineIntersections(p(0,0),2,G.lineThrough(p(-3,0),p(3,0))).points.length,2));
test("32 tangence cercle droite",()=>assert.equal(G.circleLineIntersections(p(0,0),2,G.lineThrough(p(-3,2),p(3,2))).kind,"tangent"));
test("33 intersection cercles",()=>assert.equal(G.circleCircleIntersections(p(0,0),2,p(2,0),2).points.length,2));
test("34 tangence cercles",()=>assert.equal(G.circleCircleIntersections(p(0,0),1,p(2,0),1).kind,"tangent"));
