const test=require("node:test");const assert=require("node:assert/strict");const G=require("../app/src/main/assets/engine/geometry-engine-v1.js");const p=(x,y)=>({x,y});
test("01 distance",()=>assert.equal(G.distance(p(0,0),p(3,4)),5));
test("02 milieu",()=>assert.deepEqual(G.midpoint(p(0,2),p(4,6)),p(2,4)));
test("03 vecteur",()=>assert.deepEqual(G.vector(p(1,2),p(4,6)),p(3,4)));
test("04 produit scalaire",()=>assert.equal(G.dot(p(1,2),p(3,4)),11));
