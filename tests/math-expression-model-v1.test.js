"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),M=require("../app/src/main/assets/understanding/math-expression-model-v1.js");
const a=s=>M.analyze(s);
test("01 moteur hors ligne",()=>assert.equal(M.diagnostics().offline,true));
test("02 version exposée",()=>assert.equal(M.version,"1.0.0"));
test("03 conserve la source",()=>assert.equal(a("2 + 3").source,"2 + 3"));
test("04 reconnaît une expression",()=>assert.equal(a("2 + 3").kind,"expression"));
test("05 reconnaît une équation",()=>assert.equal(a("2x + 3 = 7").kind,"equation"));
test("06 reconnaît une inégalité stricte",()=>assert.equal(a("x > 4").kind,"inequality"));
test("07 reconnaît inférieur ou égal",()=>assert.ok(a("x ≤ 5").comparisons.some(x=>x.operator==="≤")));
test("08 reconnaît supérieur ou égal ASCII",()=>assert.ok(a("x >= 5").comparisons.some(x=>x.operator===">=")));
test("09 reconnaît variable",()=>assert.ok(a("x + 2").variables.some(x=>x.name==="x")));
test("10 conserve variable grecque",()=>assert.ok(a("α + β").variables.length===2));
test("11 reconnaît constante pi",()=>assert.equal(a("πr^2").constants[0].name,"π"));
test("12 reconnaît constante e",()=>assert.equal(a("e^x").constants[0].name,"e"));
test("13 priorité multiplication avant addition",()=>{const n=a("2 + 3 * 4").ast;assert.equal(n.operator,"+");assert.equal(n.right.operator,"*");});
test("14 parenthèses regroupées",()=>assert.equal(a("(2 + 3) * 4").ast.left.type,"group"));
test("15 puissance prioritaire",()=>assert.equal(a("2 * x^2").ast.right.operator,"^"));
test("16 puissance associée à droite",()=>assert.equal(a("x^2^3").ast.right.operator,"^"));
test("17 opérateur unaire négatif",()=>assert.equal(a("-x + 2").ast.left.type,"unary"));
test("18 multiplication implicite 2x",()=>assert.equal(a("2x").ast.operator,"×"));
test("19 multiplication implicite entre parenthèses",()=>assert.equal(a("3(x+1)").ast.operator,"×"));
test("20 symbole de multiplication ×",()=>assert.equal(a("a × b").ast.operator,"×"));
test("21 point médian",()=>assert.equal(a("a · b").ast.operator,"·"));
test("22 division représentée comme fraction",()=>assert.equal(a("a/b").ast.semanticKind,"fraction"));
test("23 division avec symbole ÷",()=>assert.equal(a("a ÷ b").ast.operator,"÷"));
test("24 racine carrée Unicode",()=>assert.equal(a("√x").ast.type,"root"));
test("25 racine carrée en fonction",()=>assert.equal(a("sqrt(x)").ast.type,"function"));
test("26 fonction trigonométrique reconnue",()=>assert.equal(a("sin(x)").functions[0].name,"sin"));
test("27 fonction logarithme reconnue",()=>assert.equal(a("ln(x)").functions[0].name,"ln"));
test("28 fonction avec deux arguments",()=>assert.equal(a("max(x, 2)").functions[0].argumentCount,2));
test("29 décimale avec virgule",()=>assert.equal(a("2,5*x").ast.left.value,2.5));
test("30 notation scientifique",()=>assert.equal(a("3e8").ast.value,300000000));
test("31 parenthèse manquante signalée",()=>assert.ok(a("(x+2").issues.some(x=>x.code==="unclosed_group")));
test("32 caractère non pris en charge signalé",()=>assert.ok(a("x @ 2").issues.some(x=>x.code==="unsupported_character")));
test("33 jeton superflu signalé",()=>assert.ok(a("x + * y").issues.some(x=>x.code==="unexpected_token"||x.code==="expected_expression")));
test("34 conserve les positions source",()=>{const r=a("  x + 2  ");assert.equal(r.source.slice(r.ast.start,r.ast.end),"x + 2");});
test("35 conserve les unités candidates",()=>assert.ok(a("v = 20 m/s").unitCandidates.length>0));
test("36 distingue les constantes et variables",()=>{const r=a("π + x");assert.equal(r.constants.length,1);assert.equal(r.variables.length,1);});
test("37 ne calcule pas les expressions",()=>assert.equal(a("2+2").policy.evaluated,false));
test("38 ne résout pas les équations",()=>assert.equal(a("x+2=5").policy.solved,false));
test("39 sortie JSON sérialisable",()=>assert.doesNotThrow(()=>JSON.stringify(a("(a+b)/c"))));
test("40 syntaxe vide signalée",()=>assert.equal(a("").kind,"unparsed"));
test("41 identifiant inconnu conservé",()=>assert.equal(a("masse = m").variables[0].name,"masse"));
test("42 accolades conservées en groupe",()=>assert.equal(a("{x+1}").ast.type,"group"));
test("43 comparateur différent",()=>assert.ok(a("x ≠ 0").comparisons.length));
test("44 comparateur ASCII différent",()=>assert.ok(a("x != 0").comparisons.length));
test("45 diagnostics décrivent les limites",()=>assert.ok(M.diagnostics().limitations.length>=4));
