const test=require("node:test");const assert=require("node:assert/strict");const M=require("../app/src/main/assets/engine/math-engine-v1.js");
test("01 tokenize les nombres et opérateurs",()=>assert.equal(M.tokenize("2*x+1").length,5));
test("02 refuse les noms inconnus",()=>assert.throws(()=>M.parse("sin(x)")));
test("03 refuse le code arbitraire",()=>assert.throws(()=>M.parse("x;alert(1)")));
test("04 évalue une expression",()=>assert.equal(M.evaluate("2*x+3",4),11));
test("05 respecte les parenthèses",()=>assert.equal(M.evaluate("(x+2)*3",2),12));
test("06 respecte la priorité",()=>assert.equal(M.evaluate("2+3*4"),14));
test("07 gère les puissances",()=>assert.equal(M.evaluate("x^3",2),8));
test("08 refuse division par zéro",()=>assert.throws(()=>M.evaluate("1/0")));
test("09 convertit en polynôme",()=>assert.deepEqual(M.toPolynomial("3*x^2+2*x+1").coefficients,[1,2,3]));
test("10 simplifie un polynôme",()=>assert.equal(M.simplify("x+x+2"),"2*x + 2"));
test("11 dérive un polynôme",()=>assert.equal(M.derivative("3*x^2+2*x+1"),"6*x + 2"));
test("12 dérive une constante",()=>assert.equal(M.derivative("7"),"0"));
test("13 calcule une primitive",()=>assert.equal(M.integrate("2*x+2"),"x^2 + 2*x"));
test("14 résout équation linéaire",()=>assert.equal(M.solveLinear(2,-6).x,3));
test("15 reconnait équation impossible",()=>assert.equal(M.solveLinear(0,4).kind,"none"));
test("16 reconnait identité",()=>assert.equal(M.solveLinear(0,0).kind,"infinite"));
test("17 résout quadratique deux racines",()=>assert.deepEqual(M.solveQuadratic(1,-3,2).roots,[1,2]));
test("18 résout racine double",()=>assert.equal(M.solveQuadratic(1,2,1).kind,"double"));
test("19 reconnait absence de racine réelle",()=>assert.equal(M.solveQuadratic(1,0,1).kind,"none"));
test("20 résout polynôme quadratique",()=>assert.deepEqual(M.solvePolynomial("x^2-4").roots,[-2,2]));
test("21 résout équation avec x des deux côtés",()=>assert.equal(M.solveEquation("2*x+1","7").x,3));
test("22 résout système 2x2",()=>{const r=M.solveSystem2x2(1,1,1,-1,4,2);assert.equal(r.x,3);assert.equal(r.y,1);});
test("23 détecte système singulier",()=>assert.equal(M.solveSystem2x2(1,2,2,4,3,6).kind,"singular"));
test("24 calcule une table de valeurs",()=>assert.deepEqual(M.evaluateMany("x^2",[1,2]).map(x=>x.value),[1,4]));
test("25 vérifie une racine",()=>assert.equal(M.rootsCheck("x^2-4",[-2,2]).every(x=>x.valid),true));
test("26 repère des restrictions de domaine",()=>assert.ok(M.domainWarnings("x^-1").length));
test("27 calcule moyenne et médiane",()=>{const r=M.statistics([1,2,9]);assert.equal(r.mean,4);assert.equal(r.median,2);});
test("28 calcule pgcd",()=>assert.equal(M.gcd(18,12),6));
test("29 calcule ppcm",()=>assert.equal(M.lcm(4,6),12));
test("30 simplifie une fraction",()=>assert.deepEqual(M.fraction(6,-8),{numerator:-3,denominator:4}));
test("31 calcule pourcentage",()=>assert.equal(M.percentage(25,200),12.5));
test("32 calcule sommet de parabole",()=>assert.deepEqual(M.quadraticVertex(1,-4,3),{x:2,y:-1}));
test("33 calcule discriminant",()=>assert.equal(M.discriminant(1,-3,2),1));
test("34 limite le degré polynomial",()=>assert.throws(()=>M.toPolynomial("x^9")));
test("35 refuse les fonctions inconnues",()=>assert.throws(()=>M.evaluate("sqrt(x)",4)));
test("36 construit audit mathématique",()=>assert.ok(M.buildAudit("dériver un polynôme").topics.includes("dérivée")));
test("37 construit contexte prudent",()=>assert.match(M.toPromptContext(M.buildAudit("résoudre équation")),/domaines de définition/i));
test("38 expose diagnostics hors ligne",()=>assert.equal(M.diagnostics().offline,true));
