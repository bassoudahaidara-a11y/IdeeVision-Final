"use strict";
const test=require("node:test"),assert=require("node:assert/strict");
const MathModel=require("../app/src/main/assets/understanding/math-expression-model-v1.js");
const A=require("../app/src/main/assets/understanding/algebraic-structures-v1.js");
const a=s=>A.analyze(s,MathModel);
test("01 moteur local",()=>assert.equal(A.diagnostics().offline,true));
test("02 version",()=>assert.equal(A.version,"1.0.0"));
test("03 conserve la source",()=>assert.equal(a("x + 2 = 5").source,"x + 2 = 5"));
test("04 reconnaît une équation candidate",()=>assert.equal(a("x + 2 = 5").classification,"single_equation_candidate"));
test("05 extrait une équation",()=>assert.equal(a("x = 4").equations.length,1));
test("06 repère une variable",()=>assert.deepEqual(a("x = 4").variables,["x"]));
test("07 conserve une variable grecque",()=>assert.deepEqual(a("α = 2").variables,["α"]));
test("08 distingue inégalité",()=>assert.equal(a("x > 2").inequalities.length,1));
test("09 distingue inférieur ou égal",()=>assert.equal(a("x ≤ 2").inequalities[0].operator,"≤"));
test("10 système de deux équations",()=>assert.equal(a("x + y = 5\nx - y = 1").classification,"system_candidate"));
test("11 compte les équations du système",()=>assert.equal(a("x + y = 5\nx - y = 1").system.equationCount,2));
test("12 variables communes du système",()=>assert.deepEqual(a("x + y = 5\nx - y = 1").system.sharedVariables,["x","y"]));
test("13 système sans variable commune reste candidat",()=>assert.equal(a("x=1\ny=2").system.status,"system_candidate"));
test("14 séparation par point-virgule",()=>assert.equal(a("x=1; y=2").equations.length,2));
test("15 séparation par et",()=>assert.equal(a("x=1 et y=2").equations.length,2));
test("16 préserve index de ligne",()=>assert.equal(a("x=1\ny=2").items[1].lineIndex,1));
test("17 monôme candidat",()=>assert.equal(a("x=2").items[0].structure,"monomial"));
test("18 binôme candidat",()=>assert.equal(a("x+1=2").items[0].structure,"binomial"));
test("19 trinôme candidat",()=>assert.equal(a("x^2+x+1=0").items[0].structure,"polynomial"));
test("20 produit factorisé candidat",()=>assert.equal(a("(x+1)(x-1)=0").items[0].structure,"product_factorized_candidate"));
test("21 fraction rationnelle candidate",()=>assert.equal(a("(x+1)/(x-2)=0").items[0].structure,"fraction_rational_candidate"));
test("22 degré un candidat",()=>assert.equal(a("2x+3=0").items[0].polynomialDegree,1));
test("23 degré deux candidat",()=>assert.equal(a("x^2+2x+1=0").items[0].polynomialDegree,2));
test("24 degré constant",()=>assert.equal(a("3=0").items[0].polynomialDegree,0));
test("25 degré d'un produit",()=>assert.equal(a("x^2*x=0").items[0].polynomialDegree,3));
test("26 fraction variable non classée polynôme",()=>assert.equal(a("1/x=2").items[0].degreeKnown,false));
test("27 variables triées sans doublons",()=>assert.deepEqual(a("x+x+y=2").variables,["x","y"]));
test("28 inconnue conservée",()=>assert.ok(a("zeta+q=3").variables.includes("zeta")));
test("29 n'effectue aucune résolution",()=>assert.equal(a("x+2=5").policy.solved,false));
test("30 aucun calcul numérique",()=>assert.equal(a("2+2=4").policy.numericallyEvaluated,false));
test("31 systèmes non résolus",()=>assert.equal(a("x+y=5\nx-y=1").policy.systemsSolved,false));
test("32 aucune validation de solution",()=>assert.equal(a("x=2").policy.solutionsVerified,false));
test("33 ne déduit pas de loi physique",()=>assert.equal(a("F=m*a").policy.physicalLawsApplied,false));
test("34 analyse plusieurs inégalités",()=>assert.equal(a("x>1\ny<4").inequalities.length,2));
test("35 relation différente conservée",()=>assert.equal(a("x≠0").inequalities[0].operator,"≠"));
test("36 système et inégalité distincts",()=>{const r=a("x+y=5\nx>1");assert.equal(r.system,null);assert.equal(r.inequalities.length,1);});
test("37 sortie sérialisable",()=>assert.doesNotThrow(()=>JSON.stringify(a("x=1\ny=2"))));
test("38 diagnostics exposent les limites",()=>assert.ok(A.diagnostics().limitations.length>=4));
test("39 aucun lien réseau",()=>assert.equal(A.diagnostics().externalDependencies,undefined));
test("40 garde le statut candidat",()=>assert.equal(a("x+y=3").equations[0].status,"candidate_relation"));
test("41 système conserve les expressions d'origine",()=>assert.deepEqual(a("x=1\ny=2").system.equations,["x=1","y=2"]));
test("42 les variables communes sont comptées",()=>assert.equal(a("x+y=5\nx-y=1").metrics.sharedVariableCount,2));
test("43 expression sans équation",()=>assert.equal(a("x+y").classification,"no_equation_detected"));
test("44 degré inconnu reste null",()=>assert.equal(a("sin(x)=1").items[0].polynomialDegree,null));
test("45 fonction d'analyse accepte chaîne vide",()=>assert.equal(a("").classification,"no_equation_detected"));
