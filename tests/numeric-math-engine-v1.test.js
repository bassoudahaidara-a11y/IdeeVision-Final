"use strict";
const test=require("node:test"),assert=require("node:assert/strict");
const E=require("../app/src/main/assets/understanding/numeric-math-engine-v1.js");
const M=require("../app/src/main/assets/understanding/math-expression-model-v1.js");
const run=(s,o)=>E.analyze(s,M,o);
test("01 moteur numérique hors ligne",()=>assert.equal(E.diagnostics().offline,true));
test("02 version stable",()=>assert.equal(E.version,"1.0.0"));
test("03 addition",()=>assert.equal(run("2+3").result,5));
test("04 soustraction",()=>assert.equal(run("9-4").result,5));
test("05 multiplication",()=>assert.equal(run("6*7").result,42));
test("06 division",()=>assert.equal(run("20/4").result,5));
test("07 priorité multiplication",()=>assert.equal(run("2+3*4").result,14));
test("08 parenthèses",()=>assert.equal(run("(2+3)*4").result,20));
test("09 décimaux point",()=>assert.equal(run("1.5+2.25").result,3.75));
test("10 décimaux virgule",()=>assert.equal(run("1,5+2,5").result,4));
test("11 nombres négatifs",()=>assert.equal(run("-5+2").result,-3));
test("12 puissances",()=>assert.equal(run("2^5").result,32));
test("13 exposant négatif",()=>assert.equal(run("2^-2").result,0.25));
test("14 racine carrée symbole",()=>assert.equal(run("√(81)").result,9));
test("15 racine carrée fonction",()=>assert.equal(run("sqrt(64)").result,8));
test("16 multiplication implicite",()=>assert.equal(run("3(4+2)").result,18));
test("17 fraction par division",()=>assert.equal(run("(1+2)/3").result,1));
test("18 constante pi",()=>assert.ok(Math.abs(run("pi*2").result-2*Math.PI)<1e-10));
test("19 constante e",()=>assert.ok(Math.abs(run("e").result-Math.E)<1e-10));
test("20 nombre d'or",()=>assert.ok(Math.abs(run("phi").result-(1+Math.sqrt(5))/2)<1e-10));
test("21 sinus",()=>assert.ok(Math.abs(run("sin(0)").result)<1e-12));
test("22 cosinus",()=>assert.equal(run("cos(0)").result,1));
test("23 tangente",()=>assert.equal(run("tan(0)").result,0));
test("24 logarithme décimal",()=>assert.equal(run("log(100)").result,2));
test("25 logarithme naturel",()=>assert.equal(run("ln(e)").result,1));
test("26 exponentielle",()=>assert.ok(Math.abs(run("exp(1)").result-Math.E)<1e-10));
test("27 valeur absolue",()=>assert.equal(run("abs(-12)").result,12));
test("28 variable explicitement fournie",()=>assert.equal(run("x^2+1", {variables:{x:3}}).result,10));
test("29 plusieurs variables",()=>assert.equal(run("2*x+y",{variables:{x:4,y:3}}).result,11));
test("30 variable inconnue non évaluée",()=>{const r=run("x+2");assert.equal(r.evaluated,false);assert.ok(r.issues.some(x=>x.code==="unknown_variable"));});
test("31 unité ambiguë refusée",()=>assert.equal(run("5m").evaluated,false));
test("32 division par zéro détectée",()=>{const r=run("4/0");assert.equal(r.result,null);assert.ok(r.issues.some(x=>x.code==="division_by_zero"));});
test("33 racine négative détectée",()=>{const r=run("sqrt(-1)");assert.equal(r.result,null);assert.ok(r.issues.some(x=>x.code==="square_root_negative"));});
test("34 logarithme de zéro refusé",()=>assert.ok(run("ln(0)").issues.some(x=>x.code==="logarithm_domain_error")));
test("35 logarithme négatif refusé",()=>assert.ok(run("log(-2)").issues.some(x=>x.code==="logarithm_domain_error")));
test("36 arcsinus hors domaine refusé",()=>assert.ok(run("asin(2)").issues.some(x=>x.code==="inverse_trigonometric_domain_error")));
test("37 fonction inconnue non calculée",()=>assert.equal(run("foo(2)").evaluated,false));
test("38 opérateur non pris en charge refusé",()=>assert.equal(run("2<3").evaluated,false));
test("39 équation non résolue",()=>{const r=run("x+2=5");assert.equal(r.evaluated,false);assert.ok(r.issues.some(x=>x.code==="equation_not_solved"));});
test("40 inégalité non résolue",()=>assert.equal(run("x>3").evaluated,false));
test("41 précision réglable",()=>assert.equal(run("1/3", {precision:5}).formatted,"0.33333"));
test("42 précision bornée",()=>assert.equal(run("1/3", {precision:40}).policy.precisionDigits,15));
test("43 conserve la source",()=>assert.equal(run(" 2 + 3 ").source," 2 + 3 "));
test("44 conserve AST",()=>assert.ok(run("2+3").ast.type==="binary"));
test("45 conserve variables fournies",()=>assert.equal(run("x",{variables:{x:8}}).variables.x,8));
test("46 résultat non fini rejeté",()=>assert.equal(run("10^10000").evaluated,false));
test("47 zéro puissance négative rejeté",()=>assert.ok(run("0^-1").issues.some(x=>x.code==="zero_negative_power")));
test("48 sortie JSON sérialisable",()=>assert.doesNotThrow(()=>JSON.stringify(run("(2+3)*4"))));
test("49 ne résout pas les équations",()=>assert.equal(run("x=2").policy.solved,false));
test("50 aucune conversion d'unité",()=>assert.equal(run("2+2").policy.unitConversionsPerformed,false));
test("51 aucune simplification symbolique prétendue",()=>assert.ok(E.diagnostics().limitations.some(x=>x.includes("symboliques"))));
test("52 erreur syntaxique empêche l'évaluation",()=>assert.equal(run("(2+3").evaluated,false));
test("53 fonction avec mauvais nombre d'arguments",()=>assert.ok(run("sin(1,2)").issues.some(x=>x.code==="function_argument_count")));
test("54 racine d'un nombre positif",()=>assert.equal(run("√144").result,12));
test("55 division avec priorité",()=>assert.equal(run("10+8/2").result,14));
test("56 puissance avant addition",()=>assert.equal(run("2+3^2").result,11));
test("57 multiplication et parenthèses imbriquées",()=>assert.equal(run("2(3+(4*2))").result,22));
test("58 substitution ne modifie pas le texte source",()=>{const r=run("x+1",{variables:{x:2}});assert.equal(r.source,"x+1");assert.equal(r.result,3);});
test("59 les inconnues restent explicites",()=>assert.equal(run("a+b",{variables:{a:1}}).evaluated,false));
test("60 diagnostics documentent les limites",()=>assert.ok(E.diagnostics().limitations.length>=5));
